"""Compiles the icon font into the addon: src/viewer/ui/font_awesome_solid.{h,cpp}.

    uv run scripts/convert_fonts.py

Font Awesome Free Solid, from assets/fonts/, subset to every ICON_FA_* named under src/, looked up in
the IconsFontAwesome7.h the build fetches: an icon added to src/ draws only once this is run again.
The subset drops the hinting, kerning and layout tables ImGui 1.80 never reads and keeps the name
table, with its copyright and licence; ImGui's own binary_to_compressed_c then writes the array
ImFontAtlas::AddFontFromMemoryCompressedTTF reads. Both the header and the tool come from what the
build fetches, so configure the build first; the tool is built once into build/tools/, beside them.

The font's licence and source are in assets/fonts/NOTICES.md.
"""
import re
import subprocess
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "assets" / "fonts" / "Font Awesome 7 Free-Solid-900.otf"
OUT = ROOT / "src" / "viewer" / "ui"
NAME = "font_awesome_solid"
SOURCES = ROOT / "src"
ICON_HEADER = ROOT / "build" / "_deps" / "iconfontcppheaders-src" / "IconsFontAwesome7.h"
TOOL_SOURCE = ROOT / "build" / "_deps" / "imgui-src" / "misc" / "fonts" / "binary_to_compressed_c.cpp"
TOOL_BUILD = ROOT / "build" / "tools" / "binary_to_compressed_c"
SUBSET = ROOT / "build" / "tools" / "font_subsets" / FONT.name
UNREAD_TABLES = ["kern", "GPOS", "GSUB", "GDEF", "hdmx", "DSIG", "LTSH", "VDMX"]
TOOL_CMAKE = """cmake_minimum_required(VERSION 3.20)
project(binary_to_compressed_c CXX)
add_executable(binary_to_compressed_c "{source}")
"""


def build_tool():
    tool = TOOL_BUILD / "build" / "Release" / "binary_to_compressed_c.exe"
    if not tool.exists():
        if not TOOL_SOURCE.exists():
            sys.exit(f"no {TOOL_SOURCE}; configure the build first so imgui is fetched")
        TOOL_BUILD.mkdir(parents=True, exist_ok=True)
        (TOOL_BUILD / "CMakeLists.txt").write_text(TOOL_CMAKE.format(source=TOOL_SOURCE.as_posix()))
        subprocess.run(["cmake", "-S", TOOL_BUILD, "-B", TOOL_BUILD / "build"], check=True, capture_output=True)
        subprocess.run(["cmake", "--build", TOOL_BUILD / "build", "--config", "Release"], check=True, capture_output=True)
    return tool


def used_icons():
    """{name: codepoint} for every ICON_FA_* named under src/."""
    if not ICON_HEADER.exists():
        sys.exit(f"no {ICON_HEADER}; configure the build first so IconFontCppHeaders is fetched")
    defined = dict(re.findall(r'#define (ICON_FA_\w+) "[^"]*"\s*// U\+([0-9a-fA-F]+)', ICON_HEADER.read_text()))
    used = set()
    for source in SOURCES.rglob("*"):
        if source.suffix in (".cpp", ".h") and source.stem != NAME:
            used.update(re.findall(r"\bICON_FA_\w+", source.read_text(encoding="utf-8")))
    unknown = sorted(used - defined.keys())
    if unknown:
        sys.exit(f"not in {ICON_HEADER.name}: {', '.join(unknown)}")
    return {name: int(defined[name], 16) for name in sorted(used)}


def write_subset(codepoints):
    from fontTools import subset

    options = subset.Options()
    options.hinting = False
    options.drop_tables += UNREAD_TABLES
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    subsetter = subset.Subsetter(options)
    loaded = subset.load_font(FONT, options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(loaded)
    SUBSET.parent.mkdir(parents=True, exist_ok=True)
    subset.save_font(loaded, SUBSET, options)


def main():
    icons = used_icons()
    write_subset(icons.values())
    converted = subprocess.run([build_tool(), SUBSET, NAME], check=True, capture_output=True, text=True).stdout
    body = converted[converted.index("static const unsigned int"):].replace("static const", "const")

    generated = f"// Generated by scripts/convert_fonts.py from {FONT.name}; licence in assets/fonts/NOTICES.md.\n"
    contents = "Subset to the icons named in src/: " + ", ".join(name.removeprefix("ICON_FA_") for name in icons) + "."
    (OUT / f"{NAME}.h").write_text(
        "#pragma once\n\n"
        "// Font Awesome 7.3.1 Free Solid, Fonticons, from FortAwesome/Font-Awesome otfs/.\n"
        + generated
        + "".join(f"// {line}\n" for line in textwrap.wrap(contents, 100))
        + f"\nextern const unsigned int {NAME}_compressed_size;\n"
        f"extern const unsigned int {NAME}_compressed_data[];\n",
        newline="\n")
    (OUT / f"{NAME}.cpp").write_text(f"{generated}\n" f'#include "viewer/ui/{NAME}.h"\n\n' + body, newline="\n")
    print(f"convert_fonts: {len(icons)} icons, {SUBSET.stat().st_size} bytes subset from {FONT.stat().st_size}")


if __name__ == "__main__":
    main()
