"""Writes src/viewer/ui/map_icon_data.h: the game's icons the map draws, from assets/icons/, as PNG bytes.

    python tools/embed_icons.py

Where each image came from is in assets/icons/NOTICES.md.
"""

import os

# (array name, file in assets/icons/, what it is)
ICONS = (
    ("kAbove", "1130638.png", "a marker well above the player"),
    ("kBelow", "1130639.png", "a marker well below the player"),
)


def array(name, data):
    lines = [f"constexpr unsigned char {name}[] = {{"]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    text = [
        "#pragma once",
        "",
        "// Generated by tools/embed_icons.py from assets/icons/; where they came from is in assets/icons/NOTICES.md.",
        "namespace viewer::ui::map_icon_data {",
        "",
    ]
    for name, file, what in ICONS:
        with open(os.path.join(root, "assets", "icons", file), "rb") as f:
            data = f.read()
        text += [f"// {file}: {what}.", array(name, data), ""]
    text += ["} // namespace viewer::ui::map_icon_data", ""]

    out = os.path.join(root, "src", "viewer", "ui", "map_icon_data.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(text))
    print(out)


if __name__ == "__main__":
    main()
