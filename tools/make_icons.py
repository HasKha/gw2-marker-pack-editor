"""Writes src/viewer/ui/icon_data.h: the addon's icon in Nexus's bar, and its hover state.

A map pin with a hole, drawn here rather than kept as a binary so a change is a diff:

    python tools/make_icons.py

Nexus's own icons are 64 pixels square, light grey, and white on hover; these follow them.
"""

import math
import os
import struct
import zlib

SIZE = 64
SAMPLES = 4  # per axis, for the anti-aliased edge

CENTRE = (32.0, 25.0)
RADIUS = 17.0
TIP = (32.0, 60.0)
HOLE = 6.5


def inside(x, y):
    dx, dy = x - CENTRE[0], y - CENTRE[1]
    if dx * dx + dy * dy <= HOLE * HOLE:
        return False
    if dx * dx + dy * dy <= RADIUS * RADIUS:
        return True
    # The two lines from the tip that touch the circle: below the centre and between them.
    distance = TIP[1] - CENTRE[1]
    half_angle = math.asin(RADIUS / distance)
    if y < CENTRE[1] or y > TIP[1]:
        return False
    angle = math.atan2(abs(x - TIP[0]), TIP[1] - y)
    return angle <= half_angle


def coverage(px, py):
    hits = 0
    for sy in range(SAMPLES):
        for sx in range(SAMPLES):
            if inside(px + (sx + 0.5) / SAMPLES, py + (sy + 0.5) / SAMPLES):
                hits += 1
    return hits / (SAMPLES * SAMPLES)


def png(grey):
    rows = bytearray()
    for py in range(SIZE):
        rows.append(0)  # filter: none
        for px in range(SIZE):
            alpha = round(coverage(px, py) * 255)
            rows += bytes((grey, grey, grey, alpha))

    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0)  # 8-bit RGBA
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b"")


def array(name, data):
    lines = [f"constexpr unsigned char {name}[] = {{"]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "src", "viewer", "ui", "icon_data.h")
    text = "\n".join([
        "#pragma once",
        "",
        "// Generated by tools/make_icons.py: the icon in Nexus's bar, as PNG, and its hover state.",
        "namespace viewer::ui::icon_data {",
        "",
        array("kIcon", png(200)),
        "",
        array("kIconHover", png(255)),
        "",
        "} // namespace viewer::ui::icon_data",
        "",
    ])
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(out)


if __name__ == "__main__":
    main()
